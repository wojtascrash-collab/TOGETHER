export const avatarSize = 160;
export const maxAvatarBytes = 24 * 1024;

function fourCC(bytes, offset) {
  return String.fromCharCode(...bytes.subarray(offset, offset + 4));
}

function frameMatchesSize(bytes, kind, size) {
  if (kind === 'VP8 ') {
    if (bytes.length <= 10 || (bytes[0] & 1) || bytes[3] !== 0x9d || bytes[4] !== 1 || bytes[5] !== 0x2a) return false;
    const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
    // Compare the full words so VP8 display scaling is rejected too.
    return view.getUint16(6, true) === size && view.getUint16(8, true) === size;
  }

  if (bytes.length <= 5 || bytes[0] !== 0x2f || (bytes[4] >> 5) !== 0) return false;
  const width = 1 + bytes[1] + ((bytes[2] & 63) << 8);
  const height = 1 + (bytes[2] >> 6) + (bytes[3] << 2) + ((bytes[4] & 15) << 10);
  return width === size && height === size;
}

// Accept only static output generated by our opaque sRGB canvas. The SQL
// validator expects a simple WebP with one image chunk and no metadata.
export function simplifyCanvasWebp(bytes, size = avatarSize) {
  if (bytes.length < 26 || fourCC(bytes, 0) !== 'RIFF' || fourCC(bytes, 8) !== 'WEBP') return null;
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  if (view.getUint32(4, true) !== bytes.length - 8) return null;
  let extended = false;
  let expectsColorProfile = false;
  let hasColorProfile = false;
  let frame = null;

  for (let offset = 12; offset < bytes.length;) {
    if (offset + 8 > bytes.length) return null;
    const tag = fourCC(bytes, offset);
    const length = view.getUint32(offset + 4, true);
    const payload = offset + 8;
    const end = payload + length + (length % 2);
    if (end > bytes.length || (length % 2 && bytes[end - 1] !== 0)) return null;

    if (tag === 'VP8X') {
      if (offset !== 12 || length !== 10 || (bytes[payload] & ~0x20) ||
          bytes[payload + 1] || bytes[payload + 2] || bytes[payload + 3]) return null;
      const readDimension = index => 1 + bytes[index] + (bytes[index + 1] << 8) + (bytes[index + 2] << 16);
      if (readDimension(payload + 4) !== size || readDimension(payload + 7) !== size) return null;
      extended = true;
      expectsColorProfile = !!(bytes[payload] & 0x20);
    } else if (tag === 'ICCP') {
      if (!extended || !expectsColorProfile || hasColorProfile || frame || !length) return null;
      hasColorProfile = true;
    } else if (tag === 'VP8 ' || tag === 'VP8L') {
      if (frame || !frameMatchesSize(bytes.subarray(payload, payload + length), tag, size)) return null;
      frame = bytes.subarray(offset, end);
    } else {
      return null;
    }
    offset = end;
  }

  if (!frame || expectsColorProfile !== hasColorProfile) return null;
  const result = new Uint8Array(12 + frame.length);
  result.set(bytes.subarray(0, 12));
  result.set(frame, 12);
  new DataView(result.buffer).setUint32(4, result.length - 8, true);
  return result;
}

export function avatarDataUrl(base64) {
  const data = base64.replace(/\s/g, '');
  const type = data.startsWith('/9j/') ? 'image/jpeg' : 'image/webp';
  return 'data:' + type + ';base64,' + data;
}

export async function prepareAvatar(file) {
  if (!['image/jpeg', 'image/png', 'image/webp'].includes(file.type) || file.size > 5 * 1024 * 1024) {
    throw new Error('Wybierz obraz JPEG, PNG lub WebP do 5 MB.');
  }
  const bitmap = await createImageBitmap(file).catch(() => {
    throw new Error('Nie udało się otworzyć zdjęcia.');
  });
  try {
    const canvas = document.createElement('canvas');
    canvas.width = canvas.height = avatarSize;
    const context = canvas.getContext('2d', { alpha: false, colorSpace: 'srgb' });
    if (!context) throw new Error('Nie udało się przygotować miniatury.');
    const side = Math.min(bitmap.width, bitmap.height);
    context.fillStyle = '#ffffff';
    context.fillRect(0, 0, avatarSize, avatarSize);
    context.drawImage(bitmap, (bitmap.width - side) / 2, (bitmap.height - side) / 2,
      side, side, 0, 0, avatarSize, avatarSize);

    for (const type of ['image/webp', 'image/jpeg']) {
      for (const quality of [0.82, 0.68, 0.55, 0.4, 0.25]) {
        const blob = await new Promise(resolve => {
          try {
            canvas.toBlob(resolve, type, quality);
          } catch {
            resolve(null);
          }
        });
        if (blob?.type !== type) break;
        if (!blob.size || (type === 'image/jpeg' && blob.size > maxAvatarBytes)) continue;
        const encoded = new Uint8Array(await blob.arrayBuffer());
        const bytes = type === 'image/webp' ? simplifyCanvasWebp(encoded) : encoded;
        if (!bytes || bytes.length > maxAvatarBytes) continue;
        return {
          hex: '\\x' + Array.from(bytes, byte => byte.toString(16).padStart(2, '0')).join(''),
          base64: btoa(String.fromCharCode(...bytes)),
        };
      }
    }
    throw new Error('Nie udało się przygotować miniatury do 24 KiB. Wybierz inne zdjęcie.');
  } finally {
    bitmap.close();
  }
}
